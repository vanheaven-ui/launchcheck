import { describe, expect, it } from "vitest";
import { parseLockfile } from "@/lib/scanner/lockfiles";

describe("parseLockfile package-lock.json", () => {
  it("parses v3 packages map, skipping root and link entries", () => {
    const text = JSON.stringify({
      lockfileVersion: 3,
      packages: {
        "": { name: "app" },
        "node_modules/lodash": { version: "4.17.20" },
        "node_modules/a/node_modules/b": { version: "1.2.3" },
        "node_modules/linked": { version: "1.0.0", link: true },
        "node_modules/noversion": {},
      },
    });
    const result = parseLockfile("package-lock.json", text);
    expect(result).toEqual({
      ok: true,
      packages: [
        { name: "lodash", version: "4.17.20" },
        { name: "b", version: "1.2.3" },
      ],
    });
  });

  it("parses v1 nested dependencies", () => {
    const text = JSON.stringify({
      lockfileVersion: 1,
      dependencies: {
        lodash: {
          version: "4.17.20",
          dependencies: { "nested-dep": { version: "0.1.0" } },
        },
        react: { version: "18.3.1" },
      },
    });
    const result = parseLockfile("package-lock.json", text);
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.packages).toContainEqual({ name: "lodash", version: "4.17.20" });
      expect(result.packages).toContainEqual({ name: "nested-dep", version: "0.1.0" });
      expect(result.packages).toContainEqual({ name: "react", version: "18.3.1" });
    }
  });

  it("returns unparseable for invalid JSON", () => {
    expect(parseLockfile("package-lock.json", "{nope")).toEqual({
      ok: false,
      reason: "unparseable",
    });
  });
});

describe("parseLockfile pnpm-lock.yaml", () => {
  it("parses v9 unquoted and scoped keys with peer suffixes", () => {
    const text = [
      "lockfileVersion: '9.0'",
      "packages:",
      "  lodash@4.17.20:",
      "    resolution: {integrity: sha512-x}",
      "  '@scope/pkg@1.2.3':",
      "    resolution: {integrity: sha512-y}",
      "  react@18.3.1(react-dom@18.3.1):",
      "    resolution: {integrity: sha512-z}",
      "snapshots:",
      "  lodash@4.17.20: {}",
      "",
    ].join("\n");
    const result = parseLockfile("pnpm-lock.yaml", text);
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.packages).toEqual([
        { name: "lodash", version: "4.17.20" },
        { name: "@scope/pkg", version: "1.2.3" },
        { name: "react", version: "18.3.1" },
      ]);
    }
  });

  it("parses older /name@version and /name/version key styles", () => {
    const text = [
      "lockfileVersion: 5.4",
      "packages:",
      "  /lodash@4.17.20:",
      "    resolution: {integrity: sha512-x}",
      "  /left-pad/1.3.0:",
      "    resolution: {integrity: sha512-y}",
      "",
    ].join("\n");
    const result = parseLockfile("pnpm-lock.yaml", text);
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.packages).toEqual([
        { name: "lodash", version: "4.17.20" },
        { name: "left-pad", version: "1.3.0" },
      ]);
    }
  });

  it("ignores non-semver versions like git, file, and workspace", () => {
    const text = [
      "lockfileVersion: '9.0'",
      "packages:",
      "  lodash@4.17.20:",
      "  foo@git+https://example.com/repo.git#abc:",
      "  bar@file:../local:",
      "  baz@workspace:*:",
      "",
    ].join("\n");
    const result = parseLockfile("pnpm-lock.yaml", text);
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.packages).toEqual([{ name: "lodash", version: "4.17.20" }]);
    }
  });

  it("returns unparseable without a lockfileVersion line", () => {
    expect(parseLockfile("pnpm-lock.yaml", "packages:\n  a@1.0.0:\n")).toEqual({
      ok: false,
      reason: "unparseable",
    });
  });
});

describe("parseLockfile yarn.lock", () => {
  it("parses v1 blocks including scoped names", () => {
    const text = [
      "# THIS IS AN AUTOGENERATED FILE",
      "",
      "lodash@^4.17.20:",
      '  version "4.17.20"',
      '  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.20.tgz"',
      "",
      '"@scope/pkg@^1.0.0", "@scope/pkg@~1.0.0":',
      '  version "1.0.0"',
      "",
    ].join("\n");
    const result = parseLockfile("yarn.lock", text);
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.packages).toEqual([
        { name: "lodash", version: "4.17.20" },
        { name: "@scope/pkg", version: "1.0.0" },
      ]);
    }
  });

  it("returns unsupported for yarn berry (__metadata)", () => {
    const text = "__metadata:\n  version: 6\n  cacheKey: 8\n";
    expect(parseLockfile("yarn.lock", text)).toEqual({ ok: false, reason: "unsupported" });
  });
});

describe("parseLockfile general", () => {
  it("deduplicates name+version pairs", () => {
    const text = JSON.stringify({
      lockfileVersion: 3,
      packages: {
        "node_modules/a": { version: "1.0.0" },
        "node_modules/b/node_modules/a": { version: "1.0.0" },
      },
    });
    const result = parseLockfile("package-lock.json", text);
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.packages).toEqual([{ name: "a", version: "1.0.0" }]);
    }
  });

  it("returns unsupported for unknown filenames", () => {
    expect(parseLockfile("Cargo.lock", "anything")).toEqual({
      ok: false,
      reason: "unsupported",
    });
  });

  it("never throws on garbage input", () => {
    for (const name of ["package-lock.json", "pnpm-lock.yaml", "yarn.lock"]) {
      for (const text of ["", "\0\0\0", "{{{", "null", "[]"]) {
        expect(() => parseLockfile(name, text)).not.toThrow();
      }
    }
  });
});
